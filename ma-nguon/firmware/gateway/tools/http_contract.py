"""Generate/check HTTP consumer constants from the canonical provider boundary."""
import hashlib
import json
from pathlib import Path
import sys

GATEWAY = Path(__file__).resolve().parents[1]
ROOT = GATEWAY.parents[1]


def expected_header():
    schema = json.loads((ROOT / "docs/http-uplink-v1.schema.json").read_text(encoding="utf-8"))
    fixture_bytes = (ROOT / "tests/fixtures/http-v1.json").read_bytes()
    fixture = json.loads(fixture_bytes)
    props, limits = schema["properties"], schema["x-safewear"]
    assert fixture["request"]["version"] == props["version"]["const"]
    assert fixture["response"]["accepted"] is True
    return f'''// Generated by tools/http_contract.py; do not edit independently.
#pragma once
#include <stddef.h>
namespace safewear_http {{ namespace contract {{
constexpr unsigned kVersion = {props["version"]["const"]};
constexpr size_t kRequestBytes = {limits["max_request_bytes"]};
constexpr size_t kMessageBytes = {limits["max_message_bytes"]};
constexpr size_t kResponseBytes = {limits["max_response_bytes"]};
constexpr size_t kActiveIds = {props["active_event_ids"]["maxItems"]};
constexpr size_t kCommands = {schema["$defs"]["response"]["properties"]["commands"]["maxItems"]};
constexpr const char *kPath = "{limits["path"]}";
constexpr const char *kFixtureSha256 = "{hashlib.sha256(fixture_bytes).hexdigest()}";
}} }}
'''


def main():
    path = GATEWAY / "include/http_contract.h"
    expected = expected_header()
    if "--generate" in sys.argv:
        path.write_text(expected, encoding="utf-8", newline="\n")
    elif not path.exists() or path.read_text(encoding="utf-8") != expected:
        raise SystemExit("HTTP consumer contract drift; run gateway/tools/http_contract.py --generate")
    print("gateway HTTP schema and frozen fixture: PASS")


if __name__ == "__main__":
    main()
